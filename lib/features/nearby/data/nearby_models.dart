/// Local models for the nearby (offline, peer-to-peer) feature.
///
/// These are intentionally independent of the chat feature's message
/// model (Part B): nearby messages travel over a direct device-to-device
/// link, not through Firestore, so they carry their own delivery state
/// and a `clientId` used for dedup and queue reconciliation.
library;

/// Connection state of the nearby link.
enum NearbyConnectionState {
  idle,
  discovering,
  advertising,
  connecting,
  connected,
  disconnected,
}

/// A nearby message: same shape the user sees in chat, but stored and
/// synced locally only. `clientId` is generated by the sender and is the
/// dedup key — a message with an already-seen `clientId` is never
/// delivered or stored twice.
class NearbyMessage {
  const NearbyMessage({
    required this.clientId,
    required this.senderUid,
    required this.text,
    required this.createdAt,
    this.delivered = false,
    this.acked = false,
  });

  factory NearbyMessage.fromJson(Map<String, dynamic> json) {
    return NearbyMessage(
      clientId: json['clientId'] as String? ?? '',
      senderUid: json['senderUid'] as String? ?? '',
      text: json['text'] as String? ?? '',
      createdAt: DateTime.tryParse(json['createdAt'] as String? ?? '') ??
          DateTime.now(),
      delivered: json['delivered'] as bool? ?? false,
      acked: json['acked'] as bool? ?? false,
    );
  }

  Map<String, dynamic> toJson() => <String, dynamic>{
        'clientId': clientId,
        'senderUid': senderUid,
        'text': text,
        'createdAt': createdAt.toIso8601String(),
        'delivered': delivered,
        'acked': acked,
      };

  NearbyMessage copyWith({bool? delivered, bool? acked}) {
    return NearbyMessage(
      clientId: clientId,
      senderUid: senderUid,
      text: text,
      createdAt: createdAt,
      delivered: delivered ?? this.delivered,
      acked: acked ?? this.acked,
    );
  }

  final String clientId;
  final String senderUid;
  final String text;
  final DateTime createdAt;

  /// True once the payload reached the partner device.
  final bool delivered;

  /// True once the partner acknowledged receipt (dedup handshake).
  final bool acked;
}

/// A discovered peer device, before pairing is verified.
class NearbyPeer {
  const NearbyPeer({
    required this.endpointId,
    required this.endpointName,
    required this.presentedToken,
  });

  /// Id assigned by the nearby-connections layer for this discovery.
  final String endpointId;

  /// Human-readable device name the peer advertises.
  final String endpointName;

  /// Pairing token the peer claims. Must match the couple document's
  /// pairing token before any connection is accepted (see
  /// [NearbyService]).
  final String presentedToken;
}
